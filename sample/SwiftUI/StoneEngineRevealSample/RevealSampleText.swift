enum RevealSampleText {
    /// 読みを振った文章。
    ///
    /// 読みがあることが肝心で、見たいものはふたつある。読みは語の上に組まれ、
    /// 語といっしょに出てくること。そして読みは文字に数えないので、五文字の
    /// 語は読みが何文字あっても五文字であること
    static let ruby = "　{吾輩|わがはい}は{猫|ねこ}である。{名前|なまえ}はまだ{無|な}い。\n　どこで{生|う}れたかとんと{見当|けんとう}がつかぬ。{何|なん}でも{薄暗|うすぐら}いじめじめした{所|ところ}でニャーニャー{泣|な}いていた{事|こと}だけは{記憶|きおく}している。"

    /// 読みのない文章。文字の出方そのものを見るためのもの
    static let plain = "　ある日の暮方の事である。一人の下人が、羅生門の下で雨やみを待っていた。\n　広い門の下には、この男のほかに誰もいない。ただ、所々丹塗の剥げた、大きな円柱に、蟋蟀が一匹とまっている。"
}
